std::array<uint8_t, 7> BitmapFont::get(char ch)
{
    std::array<uint8_t, 7> result = {0};
    int idx = static_cast<unsigned char>(ch) - 32;
    if (idx >= 0 && idx < 64)
        for (int i = 0; i < 7; ++i) result[i] = kFont[idx][i];
    return result;
}

bool BitmapFont::isPrintable(char ch)
{
    int idx = static_cast<unsigned char>(ch) - 32;
    return idx >= 0 && idx < 64;
}
